CREATE OR REPLACE FUNCTION auditar_declaracion() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 INSERT INTO auditoria_declaracion(id_declaracion,id_funcionario,version,estado,datos_declarados)
 VALUES (NEW.id_declaracion,NEW.id_funcionario,NEW.version,NEW.estado,NEW.datos_declarados);
 RETURN NEW;
END $$;
CREATE TRIGGER declaracion_auditoria AFTER INSERT OR UPDATE ON declaracion FOR EACH ROW EXECUTE FUNCTION auditar_declaracion();
