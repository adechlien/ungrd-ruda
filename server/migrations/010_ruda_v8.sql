CREATE TABLE registro (
  id_registro uuid PRIMARY KEY,
  id_persona_declarante bigint NOT NULL,
  id_funcionario bigint NOT NULL,
  id_organizacion_receptora bigint NOT NULL,
  id_municipio_declaracion bigint,
  direccion_declaracion text,
  fecha_declaracion date,
  tipo_declaracion text,
  estado estado_registro NOT NULL DEFAULT 'borrador',
  version_formato smallint NOT NULL DEFAULT 5 CHECK (version_formato >= 0),
  revision_ruda smallint NOT NULL DEFAULT 8 CHECK (revision_ruda >= 0),
  version_registro integer NOT NULL DEFAULT 1 CHECK (version_registro >= 0),
  creado_en timestamptz NOT NULL DEFAULT now(),
  actualizado_en timestamptz NOT NULL DEFAULT now(),
  terminado_en timestamptz,
  CHECK (revision_ruda = 8),
  CHECK (version_registro > 0),
  CHECK ((estado = 'terminado') = (terminado_en IS NOT NULL))
