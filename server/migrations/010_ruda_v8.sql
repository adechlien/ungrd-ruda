CREATE SCHEMA ruda_legacy_v7;

DO $$ DECLARE t record; BEGIN FOR t IN SELECT tablename FROM pg_tables WHERE schemaname='public' AND tablename IN ('departamento','municipio','persona','organizacion','funcionario','categoria_evento','tipo_evento','territorio_colectivo','evento','certificacion_evento','declaracion','desplazamiento','narracion_hechos','pregunta_guia_respuesta','hogar','miembro_hogar','animal','unidad_productiva','necesidad_basica','bien_inmueble','bien_mueble','informacion_economica','afectacion_salud','comunidad','modulo_etnico','seguimiento_etnico','evento_declarado','usuario','sesion','pregunta_guia','auditoria_declaracion') LOOP EXECUTE format('ALTER TABLE public.%I SET SCHEMA ruda_legacy_v7',t.tablename); END LOOP; END $$;

CREATE TYPE estado_registro AS ENUM ('borrador','terminado');

CREATE TYPE rol_usuario AS ENUM ('funcionario','administrador');

CREATE TABLE organizacion (
  id_organizacion bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre text NOT NULL,
  tipo text
);

